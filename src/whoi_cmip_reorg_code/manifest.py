"""YAML manifests and their schemas.

- ``core.yaml``: datasets the store must hold (hand-written).
- ``repairs/<date>.yaml``: repair actions (generated by ``plan_repairs.py``).
- ``moves/<name>.yaml``: file moves (generated by ``plan_moves.py``). Only
  executable once ``approved_by`` and ``approved_on`` are filled in by hand.
- ``catalogs.yaml``: products to catalog (hand-written).
- ``products/<product>.yaml``: a reanalysis product to add: source, groups of
  files, variables, years (hand-written). Products already on disk with no
  fetch (ERA5) leave out ``source`` and may use ``{date:...}`` file names.
- ``fetch/<date>-<product>.yaml``: files to download for a product (generated
  by ``plan_product.py``; only files missing from the store).

Unknown keys are errors, so typos fail loudly.
"""

from __future__ import annotations

import itertools
import os
import re
import string
from collections import Counter
from datetime import date, datetime
from pathlib import Path, PurePosixPath
from typing import Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, field_validator, model_validator

from whoi_cmip_reorg_code import drs

CMIP6_SELECTOR_FACETS = drs.DRS_DIR_FACETS  # activity_id ... version


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


# --- core.yaml ---------------------------------------------------------------


class Requirement(_Strict):
    """One block of required datasets: the cartesian product of the listed
    facet values. Facets left out match anything."""

    name: str
    note: str | None = None
    facets: dict[str, str | list[str]]

    @field_validator("facets")
    @classmethod
    def _known_facets(cls, v: dict) -> dict:
        bad = set(v) - set(CMIP6_SELECTOR_FACETS)
        if bad:
            raise ValueError(f"unknown facets {sorted(bad)}")
        if not v:
            raise ValueError("facets must not be empty")
        for k, val in v.items():
            if isinstance(val, list) and not val:
                raise ValueError(f"facet {k} has an empty list")
        return v

    def expand(self) -> list[dict[str, str]]:
        keys = sorted(self.facets)
        vals = [
            self.facets[k] if isinstance(self.facets[k], list) else [self.facets[k]]
            for k in keys
        ]
        return [dict(zip(keys, combo)) for combo in itertools.product(*vals)]


class CoreManifest(_Strict):
    schema_version: Literal[1] = 1
    description: str | None = None
    requirements: list[Requirement] = Field(default_factory=list)

    @model_validator(mode="after")
    def _unique_names(self) -> CoreManifest:
        names = [r.name for r in self.requirements]
        dup = {n for n in names if names.count(n) > 1}
        if dup:
            raise ValueError(f"duplicate requirement names {sorted(dup)}")
        return self


# --- repairs -----------------------------------------------------------------

RepairKind = Literal["redownload", "quarantine", "report_only"]


class RepairAction(_Strict):
    action: RepairKind
    reason: str
    dataset_id: str | None = None
    # bad or suspect local file (absolute path), if any
    local_path: str | None = None
    # DRS path relative to the data root, for redownloads
    drs_rel_path: str | None = None
    url: str | None = None
    checksum: str | None = None
    checksum_type: str | None = None
    size_bytes: int | None = None
    evidence: dict[str, str | int | float | bool | None] = Field(default_factory=dict)

    @model_validator(mode="after")
    def _needs(self) -> RepairAction:
        if self.action == "redownload":
            missing = [
                k
                for k in ("drs_rel_path", "url", "checksum")
                if getattr(self, k) is None
            ]
            if missing:
                raise ValueError(f"redownload needs {missing}")
        if self.action == "quarantine" and self.local_path is None:
            raise ValueError("quarantine needs local_path")
        if self.drs_rel_path is not None:
            _check_rel(self.drs_rel_path)
        return self

    @property
    def rel_path(self) -> str | None:
        """Download target relative to the staging root (``download.run``)."""
        return self.drs_rel_path


class RepairManifest(_Strict):
    schema_version: Literal[1] = 1
    created: datetime
    created_by: str
    inputs: dict[str, str] = Field(default_factory=dict)
    actions: list[RepairAction] = Field(default_factory=list)


# --- moves -------------------------------------------------------------------

MoveKind = Literal["quarantine", "install", "reorg"]


def _check_abs(p: str) -> str:
    pp = PurePosixPath(p)
    if not pp.is_absolute() or ".." in pp.parts:
        raise ValueError(f"path must be absolute without '..': {p!r}")
    return p


def _check_rel(p: str) -> str:
    pp = PurePosixPath(p)
    if pp.is_absolute() or ".." in pp.parts or not pp.parts:
        raise ValueError(f"path must be relative without '..': {p!r}")
    return p


class Move(_Strict):
    src: str
    dst: str
    kind: MoveKind
    note: str | None = None

    @field_validator("src", "dst")
    @classmethod
    def _abs(cls, v: str) -> str:
        return _check_abs(v)

    @model_validator(mode="after")
    def _differs(self) -> Move:
        if self.src == self.dst:
            raise ValueError(f"src == dst: {self.src}")
        return self


class MoveManifest(_Strict):
    schema_version: Literal[1] = 1
    created: datetime
    created_by: str
    description: str
    # Filled in by hand after review. apply_moves --execute refuses without them.
    approved_by: str | None = None
    approved_on: date | None = None
    moves: list[Move] = Field(default_factory=list)

    @model_validator(mode="after")
    def _no_collisions(self) -> MoveManifest:
        dsts = Counter(m.dst for m in self.moves)
        srcs = Counter(m.src for m in self.moves)
        dup = [d for d, n in dsts.items() if n > 1]
        if dup:
            raise ValueError(f"several moves to the same dst: {sorted(dup)[:5]}")
        dsrc = [s for s, n in srcs.items() if n > 1]
        if dsrc:
            raise ValueError(f"same src moved twice: {sorted(dsrc)[:5]}")
        # A path may be vacated and then refilled (repair: original ->
        # quarantine, staged -> original path), but only in that order.
        src_at = {m.src: i for i, m in enumerate(self.moves)}
        bad = [m.dst for i, m in enumerate(self.moves) if src_at.get(m.dst, -1) > i]
        if bad:
            raise ValueError(
                f"dst is vacated only by a later move (chained): {sorted(bad)[:5]}"
            )
        return self

    @property
    def approved(self) -> bool:
        return bool(self.approved_by) and self.approved_on is not None


# --- products/<product>.yaml -------------------------------------------------

# Facet values go into dot-separated master_ids and directory names.
_TOKEN = re.compile(r"^[A-Za-z0-9_-]+$")
_FILE_FIELDS = {"variable", "year", "date"}
_PATH_FIELDS = {"remote_dir", "file", "variable", "year", "frequency", "level"}
# strftime directives allowed in {date:...}, and the digits each matches.
DATE_DIRECTIVES = {"%Y": r"\d{4}", "%m": r"\d{2}", "%d": r"\d{2}", "%H": r"\d{2}"}
_DATE_SPEC = re.compile(r"^(?:%[YmdH]|[-_.T]|)+$")


def _fields(template: str) -> set[str]:
    return {f for _, f, _, _ in string.Formatter().parse(template) if f is not None}


def date_spec(template: str) -> str | None:
    """The format spec of ``{date:...}`` in ``template``, or None."""
    for _, f, spec, _ in string.Formatter().parse(template):
        if f == "date":
            return spec
    return None


def _token(v: str) -> str:
    if not _TOKEN.match(v):
        raise ValueError(f"must match {_TOKEN.pattern}: {v!r}")
    return v


class Source(_Strict):
    # Fetcher plugin. Later: "cds" (ERA5), "esgf".
    kind: Literal["https_index"]
    base_url: str

    @field_validator("base_url")
    @classmethod
    def _url(cls, v: str) -> str:
        if not v.startswith("https://") or not v.endswith("/"):
            raise ValueError(f"base_url must be https:// and end with '/': {v!r}")
        return v


class GroupExpect(_Strict):
    """Checked after download; never converted. variable -> units string."""

    units: dict[str, str] = Field(default_factory=dict)


class ProductGroup(_Strict):
    """One remote directory and the variables to take from it."""

    remote_dir: str
    frequency: str
    level: str
    # File name with {variable} and optionally {year} (one file per year) or
    # {date:<strftime>} (one file per day/month, e.g. {date:%Y-%m-%d}; only
    # for local products without a source: such groups are not expanded).
    file_pattern: str
    variables: list[str]
    # On-disk token -> catalog variable_id (e.g. T2m: 2m_temperature). Files
    # keep their names; only the catalog uses the alias.
    aliases: dict[str, str] = Field(default_factory=dict)
    # [first, last], inclusive. Overrides the product's years.
    years: tuple[int, int] | None = None
    # Local path under reanalysis/<product>/. Default mirrors the remote:
    # "{remote_dir}/{file}". Fields: remote_dir file variable year frequency level.
    path_template: str | None = None
    expect: GroupExpect | None = None

    @field_validator("remote_dir")
    @classmethod
    def _rel(cls, v: str) -> str:
        return _check_rel(v.rstrip("/"))

    @field_validator("frequency", "level")
    @classmethod
    def _tok(cls, v: str) -> str:
        return _token(v)

    @field_validator("variables")
    @classmethod
    def _vars(cls, v: list[str]) -> list[str]:
        if not v:
            raise ValueError("a group needs at least one variable")
        if len(set(v)) != len(v):
            raise ValueError(f"duplicate variables {v}")
        return [_token(x) for x in v]

    @field_validator("file_pattern")
    @classmethod
    def _pattern(cls, v: str) -> str:
        f = _fields(v)
        if "variable" not in f or f - _FILE_FIELDS:
            raise ValueError(
                f"file_pattern needs {{variable}} and may only use {_FILE_FIELDS}: {v!r}"
            )
        if "/" in v:
            raise ValueError(f"file_pattern is a file name, not a path: {v!r}")
        if {"year", "date"} <= f:
            raise ValueError(f"file_pattern has both {{year}} and {{date}}: {v!r}")
        spec = date_spec(v)
        if "date" in f and (not spec or not _DATE_SPEC.match(spec)):
            raise ValueError(
                f"{{date:...}} needs a spec of {sorted(DATE_DIRECTIVES)} and -_.T: {v!r}"
            )
        return v

    @model_validator(mode="after")
    def _aliases(self) -> ProductGroup:
        bad = set(self.aliases) - set(self.variables)
        if bad:
            raise ValueError(f"aliases for unknown variables {sorted(bad)}")
        for a in self.aliases.values():
            _token(a)
        return self

    @property
    def dated(self) -> bool:
        return "date" in _fields(self.file_pattern)

    def variable_id(self, token: str) -> str:
        return self.aliases.get(token, token)

    @field_validator("path_template")
    @classmethod
    def _template(cls, v: str | None) -> str | None:
        if v is not None and _fields(v) - _PATH_FIELDS:
            raise ValueError(f"path_template may only use {_PATH_FIELDS}: {v!r}")
        return v

    @property
    def yearly(self) -> bool:
        return "year" in _fields(self.file_pattern)

    @property
    def template(self) -> str:
        return self.path_template or "{remote_dir}/{file}"


class ProductManifest(_Strict):
    schema_version: Literal[1] = 1
    product: str
    title: str
    version: str
    # Reference to cite (paper / DOI).
    citation: str | None = None
    # Text the provider asks users to put in their acknowledgments.
    acknowledgment: str | None = None
    # Data licence / terms of use, shown on the site.
    license: str | None = None
    # None: already on disk, catalog only (plan_product refuses it).
    source: Source | None = None
    years: tuple[int, int] | None = None
    groups: list[ProductGroup]

    @field_validator("product", "version")
    @classmethod
    def _tok(cls, v: str) -> str:
        return _token(v)

    @model_validator(mode="after")
    def _check(self) -> ProductManifest:
        if not self.groups:
            raise ValueError("at least one group")
        for g in self.groups:
            if g.dated and self.source is not None:
                raise ValueError(
                    f"{g.remote_dir}: {{date}} groups are catalog-only (no source)"
                )
            yrs = g.years or self.years
            if g.yearly and yrs is None:
                raise ValueError(f"{g.remote_dir}: {{year}} in file_pattern, no years")
            if yrs is not None and yrs[0] > yrs[1]:
                raise ValueError(f"{g.remote_dir}: bad year range {list(yrs)}")
        rows = self.expand()
        dup = [p for p, n in Counter(r["rel_path"] for r in rows).items() if n > 1]
        if dup:
            raise ValueError(f"several files map to the same path: {sorted(dup)[:5]}")
        # One dataset (frequency, level, variable) may come from several groups
        # (e.g. two eras in two dirs), but never with the same year twice.
        # {date} groups are not expanded, so not checked here.
        seen: dict[tuple, set] = {}
        for r in rows:
            key = (r["frequency"], r["level"], r["variable_id"])
            yrs = seen.setdefault(key, set())
            if r["year"] in yrs:
                raise ValueError(f"dataset {'.'.join(key)} has year {r['year']} twice")
            yrs.add(r["year"])
        return self

    def group_years(self, g: ProductGroup) -> list[int | None]:
        if not g.yearly:
            return [None]
        y0, y1 = g.years or self.years
        return list(range(y0, y1 + 1))

    def expand(self) -> list[dict]:
        """One row per file. ``rel_path`` is relative to the store root
        (``reanalysis/<product>/...``); ``remote_path`` to ``base_url``
        (``url`` is None without a source). ``{date}`` groups are skipped."""
        out = []
        base_url = self.source.base_url if self.source else None
        for g in self.groups:
            if g.dated:
                continue
            units = g.expect.units if g.expect else {}
            for var, year in itertools.product(g.variables, self.group_years(g)):
                fields = {"variable": var, "year": year}
                fname = g.file_pattern.format(**fields)
                local = g.template.format(
                    remote_dir=g.remote_dir,
                    file=fname,
                    frequency=g.frequency,
                    level=g.level,
                    **fields,
                )
                remote = f"{g.remote_dir}/{fname}"
                out.append(
                    {
                        "url": base_url and base_url + remote,
                        "remote_path": remote,
                        "rel_path": _check_rel(f"reanalysis/{self.product}/{local}"),
                        "product": self.product,
                        "frequency": g.frequency,
                        "level": g.level,
                        "variable_id": g.variable_id(var),
                        "year": year,
                        "expect_units": units.get(var),
                    }
                )
        return out


# --- fetch/<date>-<product>.yaml ---------------------------------------------


class FetchItem(_Strict):
    url: str
    # Relative to the store root and the staging root alike.
    rel_path: str
    size_bytes: int | None = None
    # Upstream Last-Modified, ISO 8601 UTC. Set as the file's mtime.
    remote_mtime: str | None = None
    checksum: str | None = None
    checksum_type: str | None = None
    # Post-download content checks.
    variable_id: str | None = None
    year: int | None = None
    expect_units: str | None = None

    @model_validator(mode="after")
    def _verifiable(self) -> FetchItem:
        _check_rel(self.rel_path)
        if self.size_bytes is None and self.checksum is None:
            raise ValueError(f"{self.rel_path}: needs size_bytes or checksum")
        return self


class FetchManifest(_Strict):
    schema_version: Literal[1] = 1
    created: datetime
    created_by: str
    product: str
    spec: str
    items: list[FetchItem] = Field(default_factory=list)

    @model_validator(mode="after")
    def _unique(self) -> FetchManifest:
        dup = [p for p, n in Counter(i.rel_path for i in self.items).items() if n > 1]
        if dup:
            raise ValueError(f"duplicate rel_path: {sorted(dup)[:5]}")
        return self


# --- catalogs.yaml -----------------------------------------------------------


Collection = Literal["cmip6", "reanalysis", "ocean_reanalysis", "observations"]


class PathRule(_Strict):
    """Generic builder: facets for files whose path (relative to the product
    root) matches the regex ``match`` (``re.search``). Each facet comes from
    the first matching rule that sets it."""

    match: str
    frequency: str | None = None
    level: str | None = None

    @field_validator("match")
    @classmethod
    def _regex(cls, v: str) -> str:
        re.compile(v)
        return v

    @field_validator("frequency", "level")
    @classmethod
    def _tok(cls, v: str | None) -> str | None:
        return v if v is None else _token(v)


class Product(_Strict):
    name: str
    root: str
    builder: Literal["cmip6", "reanalysis", "generic"]
    # reanalysis: the product manifest, relative to the catalogs.yaml directory
    spec: str | None = None
    output: str
    enabled: bool = True
    description: str | None = None
    # Default: the builder's own (cmip6 / reanalysis). Required for generic.
    collection: Collection | None = None
    # generic only: facet rules, version label, globs never catalogued.
    rules: list[PathRule] = Field(default_factory=list)
    version: str | None = None
    exclude_patterns: list[str] = Field(default_factory=list)
    # Shown on the site's dataset page (reanalysis: also in the product spec).
    citation: str | None = None
    license: str | None = None
    # Shown on the site's "Other holdings" page while the product is disabled.
    years: str | None = None
    caveats: str | None = None

    @field_validator("root")
    @classmethod
    def _abs(cls, v: str) -> str:
        return _check_abs(v)

    @field_validator("name", "version")
    @classmethod
    def _tok(cls, v: str | None) -> str | None:
        return v if v is None else _token(v)

    @model_validator(mode="after")
    def _spec(self) -> Product:
        if (self.builder == "reanalysis") != (self.spec is not None):
            raise ValueError(
                f"{self.name}: spec is required for, and only for, reanalysis"
            )
        if self.builder == "generic" and self.collection is None:
            raise ValueError(f"{self.name}: generic products need a collection")
        if self.builder != "generic" and (self.rules or self.version):
            raise ValueError(f"{self.name}: rules and version are for generic only")
        if self.builder == "cmip6" and self.collection not in (None, "cmip6"):
            raise ValueError(f"{self.name}: cmip6 builder is collection cmip6")
        return self

    @property
    def catalog_collection(self) -> str:
        return self.collection or ("cmip6" if self.builder == "cmip6" else "reanalysis")


class Listed(_Strict):
    """A holding shown on the site's "Other holdings" page but never
    catalogued (no builder). ``path`` is relative to the data root."""

    name: str
    path: str
    description: str
    years: str | None = None
    caveats: str | None = None
    citation: str | None = None
    license: str | None = None

    @field_validator("name")
    @classmethod
    def _tok(cls, v: str) -> str:
        return _token(v)

    @field_validator("path")
    @classmethod
    def _rel(cls, v: str) -> str:
        return _check_rel(v)


class CatalogsManifest(_Strict):
    schema_version: Literal[1] = 1
    products: list[Product]
    listed: list[Listed] = Field(default_factory=list)

    @model_validator(mode="after")
    def _unique(self) -> CatalogsManifest:
        names = [p.name for p in [*self.products, *self.listed]]
        if len(names) != len(set(names)):
            raise ValueError("duplicate product names")
        outs = [p.output for p in self.products]
        if len(outs) != len(set(outs)):
            raise ValueError("duplicate outputs")
        # Two enabled products over one tree would catalog files twice.
        roots = sorted(
            (p.root.rstrip("/") + "/", p.name) for p in self.products if p.enabled
        )
        for (a, na), (b, nb) in itertools.pairwise(roots):
            if b.startswith(a):
                raise ValueError(f"roots overlap: {na} ({a}) contains {nb} ({b})")
        return self


# --- I/O ---------------------------------------------------------------------


def load[M: BaseModel](path: str | os.PathLike, model: type[M]) -> M:
    """Load and validate a YAML manifest."""
    with open(path) as f:
        data = yaml.safe_load(f)
    return model.model_validate(data if data is not None else {})


def dump(obj: BaseModel, path: str | os.PathLike, header: str | None = None) -> Path:
    """Write a manifest as YAML (temp file, then rename)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    text = yaml.safe_dump(
        obj.model_dump(mode="json", exclude_none=False),
        sort_keys=False,
        allow_unicode=True,
        width=100,
    )
    if header:
        text = (
            "".join(f"# {ln}\n" if ln else "#\n" for ln in header.splitlines()) + text
        )
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text)
    tmp.replace(path)
    return path
