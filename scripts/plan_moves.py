"""Write a move manifest for review (touches no data files).

The manifest is written UNAPPROVED. After review, Brett fills in approved_by
and approved_on by hand; only then will apply_moves.py --execute run it. A
report parquet (same name, .parquet) lists every candidate with its status
(planned, unmappable, collision, ...).

Examples:
    # repairs: quarantine bad originals, install staged replacements
    uv run scripts/plan_moves.py repairs --repairs manifests/repairs/2026-11-20.yaml \
        --staging-root <STAGING> --quarantine-root <QUARANTINE> \
        --store-root /proj/cmip6 --drs-root /proj/cmip6/cmip6 --verify \
        --out manifests/moves/2026-11-20-repairs.yaml

    # reorganization: non-DRS files into the DRS layout
    uv run scripts/plan_moves.py reorg --scan scan/ --ncinfo ncinfo/ \
        --drs-root /proj/cmip6/cmip6 --out manifests/moves/2026-12-01-reorg.yaml
"""

from __future__ import annotations

import argparse
import getpass
import sys
from datetime import UTC, datetime
from pathlib import Path

import polars as pl

from whoi_cmip_reorg_code.manifest import MoveManifest, RepairManifest, dump, load
from whoi_cmip_reorg_code.moves import plan_reorg, plan_repair_moves


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("repairs")
    r.add_argument("--repairs", required=True)
    r.add_argument("--staging-root", required=True)
    r.add_argument("--quarantine-root", required=True)
    r.add_argument("--store-root", required=True)
    r.add_argument("--drs-root", required=True)
    r.add_argument("--verify", action="store_true", help="sha256 staged files first")
    g = sub.add_parser("reorg")
    g.add_argument("--scan", required=True)
    g.add_argument(
        "--ncinfo", help="dir of ncinfo_*.parquet (fills activity/institution)"
    )
    g.add_argument("--drs-root", required=True)
    for p in (r, g):
        p.add_argument("--out", required=True)
    args = ap.parse_args(argv)

    if args.cmd == "repairs":
        moves, report = plan_repair_moves(
            load(args.repairs, RepairManifest),
            args.staging_root,
            args.quarantine_root,
            args.store_root,
            args.drs_root,
            verify=args.verify,
        )
        desc = (
            f"Repairs from {args.repairs}: quarantine originals, install staged files"
        )
    else:
        holdings = pl.read_parquet(sorted(Path(args.scan).glob("holdings_*.parquet")))
        nci = None
        if args.ncinfo:
            nci = pl.read_parquet(sorted(Path(args.ncinfo).glob("ncinfo_*.parquet")))
        moves, report = plan_reorg(holdings, args.drs_root, nci)
        desc = f"DRS reorganization from scan {args.scan}"

    m = MoveManifest(
        created=datetime.now(UTC),
        created_by=f"plan_moves.py {args.cmd} ({getpass.getuser()})",
        description=desc,
        moves=moves,
    )
    out = Path(args.out)
    dump(
        m,
        out,
        header=(
            "Generated by scripts/plan_moves.py. UNAPPROVED.\n"
            "To approve after review, set approved_by and approved_on (YYYY-MM-DD)."
        ),
    )
    report.write_parquet(out.with_suffix(".parquet"))
    print(report.group_by("status").len().sort("status"), file=sys.stderr)
    print(f"{len(moves)} moves -> {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
