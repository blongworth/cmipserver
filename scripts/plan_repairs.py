"""Plan repairs from audit outputs (offline; touches no data files).

Writes --out (YAML, schema manifest.RepairManifest) and a Markdown review
sheet next to it (same name, .md).

Example:
    uv run scripts/plan_repairs.py --esgf esgf/ --ncinfo ncinfo/ \
        --checksums checksums/ --gaps gaps/ \
        --out manifests/repairs/2026-11-20.yaml
"""

from __future__ import annotations

import argparse
import getpass
import sys
from datetime import UTC, datetime
from pathlib import Path

import polars as pl

from whoi_cmip_reorg_code.manifest import RepairManifest, dump
from whoi_cmip_reorg_code.repairs import plan, summary_markdown


def _read(d: str | None, pattern: str) -> pl.DataFrame | None:
    if d is None:
        return None
    p = Path(d)
    files = [p] if p.is_file() else sorted(p.glob(pattern))
    if not files:
        raise SystemExit(f"no {pattern} in {d}")
    return pl.read_parquet(files)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--esgf", required=True, help="check_esgf.py output dir")
    ap.add_argument("--ncinfo", help="dir of ncinfo_*.parquet")
    ap.add_argument("--checksums", help="dir of checksums_*.parquet")
    ap.add_argument("--gaps", help="find_gaps.py output dir")
    ap.add_argument("--out", required=True, help="repairs YAML to write")
    args = ap.parse_args(argv)

    esgf = Path(args.esgf)
    actions = plan(
        pl.read_parquet(esgf / "esgf_compare.parquet"),
        pl.read_parquet(esgf / "esgf_files.parquet"),
        pl.read_parquet(esgf / "esgf_missing_local.parquet"),
        ncinfo=_read(args.ncinfo, "ncinfo_*.parquet"),
        checksums=_read(args.checksums, "checksums_*.parquet"),
        gap_issues=_read(args.gaps, "gap_issues.parquet"),
    )
    inputs = {
        k: str(Path(v).resolve())
        for k, v in vars(args).items()
        if k != "out" and v is not None
    }
    m = RepairManifest(
        created=datetime.now(UTC),
        created_by=f"plan_repairs.py ({getpass.getuser()})",
        inputs=inputs,
        actions=actions,
    )
    out = Path(args.out)
    dump(m, out, header="Generated by scripts/plan_repairs.py. Review before use.")
    md = summary_markdown(actions, f"Repair plan {out.stem}")
    out.with_suffix(".md").write_text(md)
    n = {
        a: sum(x.action == a for x in actions)
        for a in ("redownload", "quarantine", "report_only")
    }
    print(f"{n} -> {out} (+ {out.with_suffix('.md').name})", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
